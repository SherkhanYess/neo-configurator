export const guidePath = (slug) => `/catalog/guides/${slug}`;
export const guideBySlug = (slug) => GUIDES.find(g => g.slug === slug) ?? null;

/** «4 минуты», «5 минут» — для карточек и шапки статьи. */
export function minutesLabel(n) {
  const d = n % 10, h = n % 100;
  const word = d === 1 && h !== 11 ? 'минута' : d >= 2 && d <= 4 && (h < 12 || h > 14) ? 'минуты' : 'минут';
  return `${n} ${word}`;
}

/** Остальные гиды — для «Читайте также». */
export const otherGuides = (slug) => GUIDES.filter(g => g.slug !== slug);
