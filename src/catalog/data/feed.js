// Порядок в ленте и стиль каждой модели. Порядок — не цена и не алфавит:
// первой идёт та, с которой проще начать разговор.
const MODELS = [
  { model: 'Sirius',        style: 'classic' },
  { model: 'Neo',           style: 'classic' },
  { model: 'Halo',          style: 'halo'    },
  { model: 'Neo Halo',      style: 'halo'    },
  { model: 'Sirius Luxe',   style: 'luxe'    },
  { model: 'Neo Luxe',      style: 'luxe'    },
  { model: 'Halo Luxe',     style: 'luxe'    },
  { model: 'Neo Halo Luxe', style: 'luxe'    },
  { model: 'Bezel',         style: 'bezel'   },
];

/**
 * Лента: модель, её стиль, тексты и из какой комбинации она собрана.
 *
 * Комбинация нужна, чтобы попасть на страницу модели и посчитать цену —
 * в коде кольцо описывается парой «шинка + оправа», а человеку показывается
 * одно название.
 */
export function feedModels() {
  const byName = new Map(
    VALID_COMBOS.map(c => [modelName(c.shank, c.cast), c])
  );

  return MODELS.flatMap(({ model, style }, i) => {
    const combo = byName.get(model);
    if (!combo) return [];          // модель убрали из каталога — строки тоже нет
    return [{
      model,
      style,
      order: i,
      shank: combo.shank,
      cast: combo.cast,
      ...STYLE_TEXT[style],
    }];
  });
}

/** Стили, у которых есть хотя бы одна модель — пустых чипсов в ленте быть не должно. */
export function usedStyles(models) {
  const present = new Set(models.map(m => m.style));
  return STYLES.filter(s => present.has(s.id));
}
