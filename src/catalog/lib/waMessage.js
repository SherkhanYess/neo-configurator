import { leadCode } from './leadCode.js';

// Тексты сообщений, с которыми человек приходит в WhatsApp.
//
// Короткий живой текст от первого лица: менеджер читает его как начало
// разговора, а не как заявку из формы. В конце — код обращения, который
// инфоцентр читает из сделки amoCRM (lib/leadCode.js).
//
// Гравировку в текст не добавляем: она в подарок к каждой заявке, и менеджер
// упоминает её сам — в сообщении от клиента это выглядело бы как требование.

// Код — отдельной строкой с подписью. Голый «[T·ib-ОБ·m]» в конце фразы люди
// принимали за мусор и стирали перед отправкой (сделка 12544769, 14.11.2026):
// заявка приходила без источника. Подпись «Индивидуальный код» говорит, что его
// надо оставить. Инфоцентр находит код в любом месте сообщения.
export const CODE_LABEL = 'Индивидуальный код';
const withCode = (text, code) => `${text}\n\n${CODE_LABEL}: ${code}`;

const SHORT_METAL = (label) => String(label ?? '').replace(/\s*золото\s*/i, '').trim();

// «в шоуруме в Астане», а не «в Астана». Алматы не склоняется, но писать
// исключение в коде честнее, чем оставлять ошибку в сообщении, которое клиент
// отправляет от своего имени.
const CITY_IN = { 'Алматы': 'Алматы', 'Астана': 'Астане' };
const cityIn = (city) => CITY_IN[city] ?? city ?? 'Алматы';

// Цветной камень называем в сообщении прямо: цена на него считается
// отдельно, и менеджеру важно увидеть это в первой строке.
const GEM_ADJ = {
  'Зелёный': 'зелёный', 'Жёлтый': 'жёлтый', 'Розовый': 'розовый', 'Синий': 'синий',
  'Рубин': 'красный', 'Красный': 'красный', 'Фиолетовый': 'фиолетовый',
  'Чёрный': 'чёрный', 'Оранжевый': 'оранжевый',
};

/** Описание украшения одной строкой: «Sirius Овал, 1 ct, Белое золото 585». */
function piece({ model, shape, carat, metalLabel, purity, gemLabel }) {
  const gem = GEM_ADJ[gemLabel];
  return [
    [model, shape].filter(Boolean).join(' '),
    carat ? `${String(carat).replace('.', ',')} ct` : null,
    gem ? `${gem} бриллиант` : null,
    metalLabel ? `${SHORT_METAL(metalLabel)} золото ${purity ?? '585'}` : null,
  ].filter(Boolean).join(', ');
}

/**
 * Собирает текст по типу обращения.
 *
 * @param {'price'|'fitting'|'help'|'hint'|'custom'} type
 * @param {object} ctx  модель, форма, карат, металл, проба, город
 * @param {object} utm  метки входа, из которых берётся код
 * @param {'f'|'m'|'g'|'o'} page  страница, с которой нажали
 */
export function waMessage(type, ctx = {}, utm = {}, page) {
  const code = leadCode(type, utm, page);

  switch (type) {
    case 'price':
      // Без модели — общий вопрос из подвала сайта: какой шоурум, тот и пишет.
      if (!ctx.model) return withCode(`Здравствуйте! Хочу узнать про помолвочные кольца. Шоурум ${ctx.city ?? 'Алматы'}.`, code);
      return withCode(`Здравствуйте! Понравилось кольцо ${piece(ctx)}. Подскажите по наличию и деталям?`, code);
    case 'fitting':
      // Без модели (кнопка в ленте) — «кольца», а не пустое место.
      return withCode(`Здравствуйте! Хотим примерить ${[ctx.model, ctx.shape].filter(Boolean).join(' ') || 'кольца'} в шоуруме в ${cityIn(ctx.city)}. Когда можно приехать?`, code);
    case 'help':
      return withCode(`Здравствуйте! Выбираем помолвочное кольцо и не знаем, какое подойдёт. Поможете?`, code);
    case 'custom':
      return withCode(`Здравствуйте! Хочу кольцо по своему дизайну. Можно обсудить идею?`, code);
    case 'hint':
      return withCode(`Здравствуйте! Мне показали кольцо ${[ctx.model, ctx.shape].filter(Boolean).join(' ')}. Подскажите стоимость и как узнать размер?`, code);
    default:
      throw new Error(`неизвестный тип обращения: ${type}`);
  }
}
